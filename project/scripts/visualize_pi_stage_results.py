"""Create final Raspberry Pi staged ONNX comparison graphs.

This script expects the four staged Pi analysis outputs generated by
analyze_pi_results.py. It combines them into one table and creates:

- pi_stage_accuracy_latency.png
- pi_stage_exit_distribution.png
- pi_stage_comparison.csv

If the stage result files are not present yet, the script exits with a clear
message so it can be run after Raspberry Pi measurements are copied back.
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = PROJECT_ROOT.parent
DEFAULT_INPUT_DIR = PROJECT_ROOT / "results" / "hojung"
OUTPUT_DIR = PROJECT_ROOT / "results" / "final_figures"
MPL_CONFIG_DIR = OUTPUT_DIR / ".matplotlib"
MPL_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
os.environ.setdefault("MPLCONFIGDIR", str(MPL_CONFIG_DIR))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

matplotlib.rcParams["font.family"] = "DejaVu Sans"
matplotlib.rcParams["axes.unicode_minus"] = False


DPI = 300
RUNS = [
    {
        "key": "fixed_fp32",
        "label": "Fixed FP32",
        "theta_mode": "fixed",
        "precision": "FP32",
        "overall": "pi_fixed_staged_fp32_analysis_overall.csv",
        "exit": "pi_fixed_staged_fp32_analysis_by_exit.csv",
    },
    {
        "key": "fixed_int8",
        "label": "Fixed INT8",
        "theta_mode": "fixed",
        "precision": "INT8",
        "overall": "pi_fixed_staged_int8_analysis_overall.csv",
        "exit": "pi_fixed_staged_int8_analysis_by_exit.csv",
    },
    {
        "key": "dynamic_fp32",
        "label": "Dynamic FP32",
        "theta_mode": "dynamic",
        "precision": "FP32",
        "overall": "pi_dynamic_staged_fp32_analysis_overall.csv",
        "exit": "pi_dynamic_staged_fp32_analysis_by_exit.csv",
    },
    {
        "key": "dynamic_int8",
        "label": "Dynamic INT8",
        "theta_mode": "dynamic",
        "precision": "INT8",
        "overall": "pi_dynamic_staged_int8_analysis_overall.csv",
        "exit": "pi_dynamic_staged_int8_analysis_by_exit.csv",
    },
]
COLORS = ["#1F5A93", "#D95F02", "#12A1A6", "#0D7377"]
EXIT_COLORS = ["#3AAFA9", "#F4A261", "#E76F51"]


def display_path(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def percent(value: float) -> float:
    return round(float(value) * 100, 2)


def load_stage_summary(input_dir: Path = DEFAULT_INPUT_DIR) -> pd.DataFrame:
    missing: list[Path] = []
    rows: list[dict[str, object]] = []

    for run in RUNS:
        overall_path = input_dir / run["overall"]
        exit_path = input_dir / run["exit"]
        if not overall_path.exists():
            missing.append(overall_path)
        if not exit_path.exists():
            missing.append(exit_path)
        if missing:
            continue

        overall = pd.read_csv(overall_path).iloc[0].to_dict()
        exit_df = pd.read_csv(exit_path)
        exit_rates = {int(row["exit_point"]): float(row["rate"]) for _, row in exit_df.iterrows()}

        rows.append(
            {
                "key": run["key"],
                "model": run["label"],
                "theta_mode": run["theta_mode"],
                "precision": run["precision"],
                "samples": int(overall["samples"]),
                "accuracy_percent": percent(overall["accuracy"]),
                "avg_inference_ms": float(overall["avg_inference_ms"]),
                "avg_sample_std_ms": float(overall.get("avg_sample_std_ms", 0.0)),
                "p50_inference_ms": float(overall["p50_inference_ms"]),
                "p95_inference_ms": float(overall["p95_inference_ms"]),
                "measurement_repeats": int(overall.get("measurement_repeats", 1)),
                "exit1_percent": percent(exit_rates.get(1, 0.0)),
                "exit2_percent": percent(exit_rates.get(2, 0.0)),
                "exit3_percent": percent(exit_rates.get(3, 0.0)),
            }
        )

    if missing:
        missing_text = "\n".join(f"- {display_path(path)}" for path in missing)
        raise FileNotFoundError(
            "Missing Raspberry Pi stage analysis files. Run analyze_pi_results.py for all four stage runs first:\n"
            f"{missing_text}"
        )

    return pd.DataFrame(rows)


def plot_accuracy_latency(df: pd.DataFrame) -> Path:
    x = np.arange(len(df))
    accuracy = df["accuracy_percent"].to_numpy(dtype=float)
    latency = df["avg_inference_ms"].to_numpy(dtype=float)
    latency_std = df["avg_sample_std_ms"].to_numpy(dtype=float)

    fig, ax1 = plt.subplots(figsize=(10.5, 6.2))
    ax2 = ax1.twinx()

    bars = ax1.bar(x, accuracy, width=0.52, color=COLORS, edgecolor="white", linewidth=1.2)
    for bar, value in zip(bars, accuracy):
        ax1.text(
            bar.get_x() + bar.get_width() / 2,
            value + 0.8,
            f"{value:.1f}%",
            ha="center",
            va="bottom",
            fontsize=11,
            fontweight="bold",
        )

    for pair in ([0, 1], [2, 3]):
        ax2.errorbar(
            x[pair],
            latency[pair],
            yerr=latency_std[pair],
            color="#111827",
            marker="D",
            markersize=7,
            linewidth=2.2,
            capsize=4,
        )
        improvement = (latency[pair[0]] - latency[pair[1]]) / latency[pair[0]] * 100
        ax2.annotate(
            f"{improvement:.1f}% faster",
            xy=((x[pair[0]] + x[pair[1]]) / 2, min(latency[pair]) - 0.12),
            ha="center",
            va="top",
            fontsize=9,
            color="#111827",
            fontweight="bold",
        )
    for xi, value in zip(x, latency):
        ax2.text(xi + 0.08, value, f"{value:.4f}ms", ha="left", va="center", fontsize=9)

    ax1.set_xticks(x)
    ax1.set_xticklabels(df["model"], fontsize=10)
    ax1.set_ylim(0, 105)
    ax1.set_ylabel("Accuracy (%)")
    ax1.yaxis.grid(True, linestyle="--", alpha=0.35)
    ax1.set_axisbelow(True)
    ax1.spines[["top"]].set_visible(False)

    ax2.set_ylabel("Avg inference time (ms)")
    ax2.spines[["top"]].set_visible(False)

    fig.suptitle("Raspberry Pi Staged ONNX: Accuracy and Latency", fontsize=15, fontweight="bold", y=0.98)
    fig.text(
        0.5,
        0.02,
        "Bar: accuracy, paired line: FP32 to INT8 latency change within each theta mode.",
        ha="center",
        fontsize=9,
    )
    fig.tight_layout(rect=(0, 0.04, 1, 0.96))

    out = OUTPUT_DIR / "pi_stage_accuracy_latency.png"
    fig.savefig(out, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    return out


def plot_exit_distribution(df: pd.DataFrame) -> Path:
    labels = df["model"].tolist()
    values = df[["exit1_percent", "exit2_percent", "exit3_percent"]].to_numpy(dtype=float)

    fig, ax = plt.subplots(figsize=(10.2, 6.0))
    x = np.arange(len(labels))
    bottom = np.zeros(len(labels))

    for idx, (name, color) in enumerate(zip(["Exit 1", "Exit 2", "Exit 3"], EXIT_COLORS)):
        bars = ax.bar(x, values[:, idx], bottom=bottom, width=0.56, color=color, edgecolor="white", label=name)
        for bar, value, base in zip(bars, values[:, idx], bottom):
            if value >= 4:
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    base + value / 2,
                    f"{value:.1f}%",
                    ha="center",
                    va="center",
                    fontsize=9,
                    color="white",
                    fontweight="bold",
                )
            elif value > 0:
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    base + value + 1.0,
                    f"{value:.1f}%",
                    ha="center",
                    va="bottom",
                    fontsize=8,
                    color="#1F2937",
                    fontweight="bold",
                )
        bottom += values[:, idx]

    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=10)
    ax.set_ylim(0, 100)
    ax.set_ylabel("Exit rate (%)")
    ax.set_title("Raspberry Pi Staged ONNX Exit Distribution", fontsize=14, fontweight="bold")
    ax.yaxis.grid(True, linestyle="--", alpha=0.35)
    ax.set_axisbelow(True)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.08), ncol=3)

    out = OUTPUT_DIR / "pi_stage_exit_distribution.png"
    fig.savefig(out, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    return out


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    try:
        df = load_stage_summary(DEFAULT_INPUT_DIR)
    except FileNotFoundError as exc:
        print(exc)
        return

    comparison_csv = OUTPUT_DIR / "pi_stage_comparison.csv"
    df.to_csv(comparison_csv, index=False)

    outputs = [
        comparison_csv,
        plot_accuracy_latency(df),
        plot_exit_distribution(df),
    ]

    print("Raspberry Pi stage comparison outputs:")
    for output in outputs:
        print(f"- {display_path(output)}")


if __name__ == "__main__":
    main()
